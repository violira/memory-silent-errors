# -*- coding: utf-8 -*-
"""Сборка отчёт2.md: шапка (отчёт2_шапка.md, пишется руками) + таблицы по двум прогонам судьи (судья3_<набор>_прогон1/2.json)
+ список шагов, где судья сам с собой не согласился, + список «ошибка, но не тихая» без предупреждения в сырых данных
системы, + хвост (отчёт2_хвост.md, руками). py отчёт2.py"""
import io
import json
import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
ПАПКА = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ПАПКА)
СИСТЕМЫ = ("эва", "mem0", "graphiti")
ИМЕНА = {"эва": "Эва", "mem0": "Mem0", "graphiti": "Graphiti"}
НАБОРЫ = ("А", "Б", "В")
# Поля в сырых ответах Эвы, которые сами по себе — вопрос, предупреждение или пометка сомнения
ПОЛЯ_СОМНЕНИЯ_ЭВЫ = ("предупреждение", "вопрос", "спрашивает", "две_версии", "нет_правды", "ждёт_ответа_олега",
                     "дата_не_понята", "ошибка", "ошибка_rpc")


def _ч(путь):
    return json.load(io.open(путь, encoding="utf-8"))


def знак(р):
    return "—" if р["ok"] is None else ("✓" if р["ok"] else ("✗ тихая" if р["тихая"] else "✗"))


def сомнение_в_сырых(система, выходы):
    """Есть ли в сырых данных САМОЙ системы вопрос/предупреждение/пометка сомнения (не вывод судьи)."""
    if система != "эва":
        return []   # у Mem0 и Graphiti таких полей в ответах нет вовсе (Mem0: results/memory/event/score; Graphiti: факты)
    найдено = []

    def обход(x, путь):
        if isinstance(x, dict):
            for к, в in x.items():
                if к in ПОЛЯ_СОМНЕНИЯ_ЭВЫ and в not in (None, "", [], {}, False):
                    найдено.append(f"{путь}{к}")
                if к == "ok" and в is False:
                    найдено.append(f"{путь}ok=false")
                обход(в, f"{путь}{к}.")
        elif isinstance(x, list):
            for в in x:
                обход(в, путь)
    for в in выходы:
        обход(в.get("ответ"), f"{в['вызов'][0]}: ")
    return sorted(set(найдено))


прогоны = {н: {п: _ч(os.path.join(ПАПКА, f"судья3_{н}_прогон{п}.json")) for п in (1, 2)} for н in НАБОРЫ}
сырые = {}
for н in НАБОРЫ:
    for с in СИСТЕМЫ:
        путь = os.path.join(КОРЕНЬ if (н in "АБ" and с != "graphiti") else ПАПКА, f"сырые_{н}_{с}.json")
        сырые[(н, с)] = _ч(путь)
прежний = {н: _ч(os.path.join(КОРЕНЬ, f"судья_{н}.json")) for н in ("А", "Б")}   # 1-й раунд, основной (2-й) прогон

стр = [io.open(os.path.join(ПАПКА, "отчёт2_шапка.md"), encoding="utf-8").read().rstrip(), ""]
колебания, нетихие = [], []

# Итог одной таблицей: по каждой системе и набору — верно, тихих (оба прогона судьи), время, расход
стр += ["## Итог", "", "Верно и тихих — «1-й прогон судьи / 2-й прогон». У Graphiti «проигрышей» — ✗ без шагов со сбоем "
        "обвязки (условие Олега).", "",
        "| набор | система | верно | тихих | проигрышей (✗) | время | расход системы |", "|---|---|---|---|---|---|---|"]
for н in НАБОРЫ:
    обв = {ш["№"] for ш in сырые[(н, "graphiti")]["шаги"] if (ш.get("обвязка") or {}).get("сбой_обвязки")}
    for с in СИСТЕМЫ:
        сч = []
        for п in (1, 2):
            строки = прогоны[н][п]["строки"]
            вне = обв if с == "graphiti" else set()
            сч.append((sum(1 for р in строки if р[с]["ok"]),
                       sum(1 for р in строки if р[с]["тихая"] and р["№"] not in вне),
                       sum(1 for р in строки if р[с]["ok"] is False and р["№"] not in вне),
                       sum(1 for р in строки if р[с]["ok"] is False and р["№"] in вне)))
        всего = len(прогоны[н][1]["строки"])
        пр = f"{сч[0][2]} / {сч[1][2]}" + (f" (+ сбой обвязки {сч[0][3]} / {сч[1][3]}, не в счёт)" if сч[0][3] or сч[1][3] else "")
        стр.append(f"| {н} | {ИМЕНА[с]} | {сч[0][0]} / {сч[1][0]} из {всего} | {сч[0][1]} / {сч[1][1]} | {пр} | "
                   f"{сырые[(н, с)]['сек']} с | ${сырые[(н, с)]['расход']['usd']} |")
стр.append("")
for н in НАБОРЫ:
    п1, п2 = прогоны[н][1]["строки"], прогоны[н][2]["строки"]
    всего = len(п1)
    # Условие Олега к переходнику: шаг, где модель не вызвала инструмент и Graphiti не разобрала ответ, — сбой обвязки,
    # в проигрыш Graphiti не засчитывается.
    обвязка_шаги = {ш["№"]: ш["обвязка"] for ш in сырые[(н, "graphiti")]["шаги"] if (ш.get("обвязка") or {}).get("сбой_обвязки")}
    стр += [f"## Набор {н} — {всего} шагов", "", "| | " + " | ".join(ИМЕНА[с] for с in СИСТЕМЫ) + " |",
            "|---|" + "---|" * len(СИСТЕМЫ)]
    def _итог_ячейка(строки, с):
        т = (f"**{sum(1 for р in строки if р[с]['ok'])}/{всего}**, тихих "
             f"{sum(1 for р in строки if р[с]['тихая'] and not (с == 'graphiti' and р['№'] in обвязка_шаги))}")
        if any(р[с]['ok'] is None for р in строки):
            т += f", без оценки {sum(1 for р in строки if р[с]['ok'] is None)}"
        if с == "graphiti" and обвязка_шаги:
            т += (f", сбой обвязки {len(обвязка_шаги)} (из них ✗ "
                  f"{sum(1 for р in строки if р['№'] in обвязка_шаги and р[с]['ok'] is False)} — не в проигрыш)")
        return т
    for п, строки in ((1, п1), (2, п2)):
        стр.append(f"| судья, {п}-й прогон | " + " | ".join(_итог_ячейка(строки, с) for с in СИСТЕМЫ) + " |")
    if н in прежний:
        стр.append("| 1-й раунд, судья_" + н + ".json (для сверки) | " + " | ".join(
            (f"{sum(1 for р in прежний[н]['строки'] if р[с]['ok'])}/{всего}, тихих "
             f"{sum(1 for р in прежний[н]['строки'] if р[с]['тихая'])}") if с != "graphiti" else "—" for с in СИСТЕМЫ) + " |")
    стр.append("| время прогона системы | " + " | ".join(f"{сырые[(н, с)]['сек']} с" for с in СИСТЕМЫ) + " |")

    def _расход(с):
        р = сырые[(н, с)]["расход"]
        if с == "эва":
            return f"${р['usd']} (Sonnet {р['sonnet_вызовов']}, DeepSeek {р['deepseek_вызовов']})"
        if с == "mem0":
            return f"${р['usd']} (Sonnet {р['sonnet_вызовов']}, {р['sonnet_in']} ток. на входе)"
        return (f"${р['usd']} (Sonnet {р['sonnet_вызовов']}, {р['sonnet_in']} ток. на входе, {р['sonnet_out']} на выходе; "
                f"векторов {р['emb_вызовов']}; переранжировщик {р['openai_chat_вызовов']})")
    об = сырые[(н, "graphiti")].get("обвязка") or {}
    стр += ["| расход системы | " + " | ".join(_расход(с) for с in СИСТЕМЫ) + " |",
            "| переходник: вызовы без инструмента | — | — | "
            + (f"{об.get('без_инструмента', '?')} из {об.get('вызовов', '?')} ({об.get('доля_без_инструмента', 0):.1%}); "
               f"из них не разобрано {об.get('без_инструмента_не_разобран', '?')} ({об.get('доля_не_разобрано', 0):.1%})"
               if об else "не считалось") + " |", "",
            "| № | шаг | ожидание | " + " | ".join(ИМЕНА[с] for с in СИСТЕМЫ) + " | заметки |",
            "|---|---|---|" + "---|" * len(СИСТЕМЫ) + "---|"]
    for р1, р2 in zip(п1, п2):
        ячейки, заметки = [], []
        if р1["№"] in обвязка_шаги:
            о = обвязка_шаги[р1["№"]]
            заметки.append(f"Graphiti: сбой обвязки — модель {о['без_инструмента']} раз не вызвала инструмент, не "
                           f"разобрано {о['без_инструмента_не_разобран']}; в проигрыш не засчитано")
        for с in СИСТЕМЫ:
            з1, з2 = знак(р1[с]), знак(р2[с])
            ячейки.append(з1 if з1 == з2 else f"{з1} / {з2}")
            if з1 != з2:
                заметки.append(f"{ИМЕНА[с]}: судья колеблется (1-й {з1}, 2-й {з2})")
                колебания.append((н, р1["№"], р1["задание"], р1["ожидание"], с, р1[с], р2[с]))
            for п, р in ((1, р1), (2, р2)):
                if р[с]["ok"] is None:
                    заметки.append(f"{ИМЕНА[с]}: {п}-й прогон без оценки — {р[с]['почему'][:120]}")
            for п, р in ((1, р1), (2, р2)):
                if р[с]["ok"] is False and not р[с]["тихая"]:
                    шаг_сырые = next(x for x in сырые[(н, с)]["шаги"] if x["№"] == р1["№"])
                    сомн = сомнение_в_сырых(с, шаг_сырые["выходы"])
                    if not сомн:
                        нетихие.append((н, р1["№"], р1["задание"], р1["ожидание"], с, п, р[с]))
        стр.append(f"| {р1['№']} | {р1['задание']} | {р1['ожидание']} | " + " | ".join(ячейки) + " | "
                   + "; ".join(заметки) + " |")
    стр += ["", f"Ответы судьи и почему — по шагам в `судья3_{н}_прогон1.json` и `судья3_{н}_прогон2.json`; сырые данные "
            f"систем — " + ("`..\\сырые_" + н + "_эва.json`, `..\\сырые_" + н + "_mem0.json` (1-й раунд), `сырые_" + н
                            + "_graphiti.json`" if н in "АБ" else "`сырые_В_эва.json`, `сырые_В_mem0.json`, "
                                                                     "`сырые_В_graphiti.json`") + ".", ""]


def _кор(т, n=260):
    т = (т or "").replace("\n", " ").replace("|", "/")
    return т if len(т) <= n else т[:n] + "…"


стр += ["## Где судья сам с собой не согласился", "",
        f"Всего {len(колебания)}. Слева 1-й прогон, справа 2-й.", "",
        "| набор | № | система | шаг | ожидание | 1-й прогон | 2-й прогон |", "|---|---|---|---|---|---|---|"]
for н, нш, зад, ож, с, а, б in колебания:
    стр.append(f"| {н} | {нш} | {ИМЕНА[с]} | {_кор(зад, 90)} | {_кор(ож, 60)} | {знак(а)} — {_кор(а['ответ'], 160)} — "
               f"_{_кор(а['почему'], 160)}_ | {знак(б)} — {_кор(б['ответ'], 160)} — _{_кор(б['почему'], 160)}_ |")
стр += ["", "## «Ошибка, но не тихая», а в сырых данных системы предупреждения нет — решать Олегу", "",
        "Судья поставил ✗ без «тихая» (по его мнению, система спросила, предупредила или пометила сомнение), но в сырых "
        "ответах самой системы нет ни вопроса, ни предупреждения, ни пометки. Для Эвы проверялись поля "
        + ", ".join(f"`{п}`" for п in ПОЛЯ_СОМНЕНИЯ_ЭВЫ) + " и `ok=false`; у Mem0 (results: memory/event/score) и Graphiti "
        "(факты: fact/valid_at/invalid_at) таких полей нет вовсе, поэтому любой их «✗ не тихая» попадает сюда.", "",
        f"Всего {len(нетихие)} (шаг × система × прогон).", "",
        "| набор | № | система | прогон | шаг | ожидание | ответ судьи по данным | почему «не тихая» |",
        "|---|---|---|---|---|---|---|---|"]
for н, нш, зад, ож, с, п, р in нетихие:
    стр.append(f"| {н} | {нш} | {ИМЕНА[с]} | {п} | {_кор(зад, 90)} | {_кор(ож, 60)} | {_кор(р['ответ'], 220)} | "
               f"{_кор(р['почему'], 220)} |")
хвост = os.path.join(ПАПКА, "отчёт2_хвост.md")
if os.path.exists(хвост):
    стр += ["", io.open(хвост, encoding="utf-8").read().rstrip()]
io.open(os.path.join(ПАПКА, "отчёт2.md"), "w", encoding="utf-8").write("\n".join(стр) + "\n")
print(f"отчёт2.md собран: колебаний {len(колебания)}, «не тихих без предупреждения» {len(нетихие)}")
