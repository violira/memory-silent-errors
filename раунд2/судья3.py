def _запись(з):
    if not isinstance(з, dict):
        return з
    out = {}
    for к in _ЗАПИСЬ_ПОЛЯ:
        в = з.get(к)
        if в in (None, "", [], False):
            continue
        if к in ("история", "версии", "назначено", "заменила", "до_неё"):
            в = [_запись(x) for x in в]
        elif к == "замена":
            в = _запись(в)
        out[к] = в
    return out


def сжать_эва(кнопка, о):
    if not isinstance(о, dict):
        return о
    if кнопка == "remember":
        т = о.get("тема_решена") or {}
        return {к: в for к, в in {
            "ok": о.get("ok"), "ошибка": о.get("ошибка"), "уже_было": о.get("уже_было"), "запись": _запись(о.get("запись")),
            "связь": о.get("связь"), "решение_о_теме": {к: т.get(к) for к in ("решение", "id", "причина", "вид_даты",
                                                                              "дата_не_понята", "почему") if т.get(к)},
            "дата_действия": о.get("дата_действия"), "вопрос": о.get("вопрос"), "предупреждение": о.get("предупреждение"),
            "заметка": о.get("заметка")}.items() if в not in (None, "", {}, [])}
    if кнопка == "correct":
        return {"ok": о.get("ok"), "ошибка": о.get("ошибка"), "было": _запись(о.get("было")), "стало": _запись(о.get("стало"))}
    if кнопка == "what_is_true":
        return {"ok": о.get("ok"), "ошибка": о.get("ошибка"), "на_день": о.get("на_день"),
                "правда": [_запись(п) for п in о.get("правда") or []]}
    if кнопка == "recall":
        return {"записи": [_запись(з) for з in о.get("записи") or []],
                "утверждения": [{"текст": у.get("текст"), "источник": у.get("источник"), "проверено": у.get("проверено")}
                                for у in о.get("утверждения") or []],
                "догадки": [д.get("текст") for д in о.get("догадки") or []]}
    if кнопка == "what_changed":
        return {"сегодня": о.get("сегодня"), "новые": [_запись(з) for з in о.get("новые") or []],
                "снятые": [_запись(з) for з in о.get("снятые") or []], "назначено": [з.get("строка") for з in о.get("назначено") or []]}
    return о


def сжать_mem0(о):
    if isinstance(о, dict):
        return {к: сжать_mem0(в) for к, в in о.items() if к not in _ЛИШНЕЕ_MEM0 and в not in (None, "", {}, [])}
    if isinstance(о, list):
        return [сжать_mem0(x) for x in о]
    return о


def сжать_graphiti(о):
    """Найденные факты Graphiti с их датами: fact, valid_at, invalid_at (null — даты нет). Порядок — как отдала система."""
    return {"факты": [{"fact": р.get("fact"), "valid_at": р.get("valid_at"), "invalid_at": р.get("invalid_at")}
                      for р in (о or {}).get("edges") or []]}


def данные(система, выходы):
    out = []
    for в in выходы:
        if "сбой" in в:
            out.append({"вызов": в["вызов"], "сбой": в["сбой"]})
            continue
        if система == "эва":
            кнопка, арг = в["вызов"]
            out.append({"кнопка": кнопка, "аргументы": арг, "ответ": сжать_эва(кнопка, в["ответ"])})
        elif система == "mem0":
            оп = в["вызов"]
            out.append({"действие": оп[0], **({"сообщение": {"role": оп[1], "content": оп[2]}} if оп[0] == "add" else {}),
                        **({"запрос": оп[1]} if оп[0] == "search" else {}), "ответ": сжать_mem0(в["ответ"])})
        else:
            оп = в["вызов"]
            out.append({"действие": {"add_episode": "add_episode", "search": "search",
                                     "get_by_group_ids": "все факты"}[оп[0]],
                        **({"эпизод": оп[1], "reference_time": оп[2]} if оп[0] == "add_episode" else {}),
                        **({"запрос": оп[1]} if оп[0] == "search" else {}), "ответ": сжать_graphiti(в["ответ"])})
    return out


def судить(шаг, система, выходы, подсказка_ответ):
    д = данные(система, выходы)
    if any("сбой" in x for x in д):
        return {"данные": д, "ответ": "", "ok": None, "тихая": None, "почему": "СБОЙ вызова — разобрать вручную"}
    сырые = json.dumps(д, ensure_ascii=False, indent=1)
    о = спросить(подсказка_ответ, f"Шаг: {шаг['вопрос']}\n\nДанные системы памяти:\n{сырые}", СХ_ОТВЕТ)
    ответ = о.get("ответ", "") if not (о.get("_отказ") or о.get("_сбой")) else ""
    if not ответ:
        return {"данные": д, "ответ": "", "ok": None, "тихая": None, "почему": f"судья не ответил: {о}"}
    с = спросить(ПОДСКАЗКА_СВЕРКА, f"Шаг: {шаг['задание']}\nОжидание: {шаг['ожидание']}\nСправка: {шаг.get('справка') or '—'}\n"
                                   f"Ответ: {ответ}\n\nСырые данные системы:\n{сырые}", СХ_СВЕРКА)
    return {"данные": д, "ответ": ответ, "ok": с.get("ok"), "тихая": с.get("тихая"), "почему": с.get("почему", str(с))}


def _путь_сырых(имя, система):
    if имя in ("А", "Б") and система in ("эва", "mem0"):
        return os.path.join(КОРЕНЬ, f"сырые_{имя}_{система}.json")   # прошлый раунд, только чтение
    return os.path.join(ПАПКА, f"сырые_{имя}_{система}.json")


t0 = time.time()
итоги = {}
for имя, набор in НАБОРЫ:
    сырые = {с: json.load(io.open(_путь_сырых(имя, с), encoding="utf-8")) for с in СИСТЕМЫ}
    задачи = {}
    with cf.ThreadPoolExecutor(max_workers=6) as пул:
        for ш in набор:
            for с in СИСТЕМЫ:
                шаг_с = next((x for x in сырые[с]["шаги"] if x["№"] == ш["№"]), None)
                if шаг_с is None:
                    continue
                задачи[(ш["№"], с)] = пул.submit(судить, ш, с, шаг_с["выходы"], ПОДСКАЗКА_ОТВЕТ_ПО_НАБОРУ[имя])
    строки = []
    for ш in набор:
        строки.append({"№": ш["№"], "задание": ш["задание"], "ожидание": ш["ожидание"], "справка": ш.get("справка", ""),
                       **{с: (задачи[(ш["№"], с)].result() if (ш["№"], с) in задачи else
                              {"данные": [], "ответ": "", "ok": None, "тихая": None, "почему": "шага нет в сырых данных"})
                          for с in СИСТЕМЫ}})
    итоги[имя] = {"строки": строки, "сек": {с: сырые[с]["сек"] for с in сырые},
                  "расход": {с: сырые[с]["расход"] for с in сырые}, "прогон_судьи": ПРОГОН}
    json.dump(итоги[имя], io.open(os.path.join(ПАПКА, f"судья3_{имя}_прогон{ПРОГОН}.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    print(f"набор {имя}: судья готов", flush=True)

судья_usd = round((РАСХОД["in"] * 2.0 + РАСХОД["out"] * 10.0) / 1_000_000, 4)


def знак(р):
    return "—" if р["ok"] is None else ("✓" if р["ok"] else ("✗ тихая" if р["тихая"] else "✗"))


