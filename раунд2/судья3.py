def _env():
    из = {}
    for с in io.open(r"C:\EVA_MEMORY\.env", encoding="utf-8-sig", errors="ignore").read().splitlines():
        с = с.strip()
        if с and not с.startswith("#") and "=" in с:
            к, _, з = с.partition("=")
            из[к.strip()] = з.strip().strip('"').strip("'")
    return из


