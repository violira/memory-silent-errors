def _з(нш, фраза, ожидание="—", справка=""):
    return {"№": нш, "задание": f"Запомни: Олег сказал, {фраза}.", "ожидание": ожидание,
            "справка": справка or ("Олег ожидания не задал: засчитывать, если записано и ничего не потеряно" if ожидание == "—" else ""),
            "эва": [("remember", {"what": фраза, "who": "Олег", "quote": фраза})],
            "mem0": [("add", "user", фраза)],
            "вопрос": f"Олег сказал: «{фраза}». {ЗАПИСЬ}"}


def _п(нш, вопрос, ожидание, эва, mem0=None, справка=""):
    return {"№": нш, "задание": вопрос, "ожидание": ожидание, "справка": справка, "эва": эва,
            "mem0": mem0 or [("search", вопрос)], "вопрос": вопрос}


def _wit(subject, on_date=""):
    return ("what_is_true", dict({"subject": subject}, **({"on_date": on_date} if on_date else {})))


