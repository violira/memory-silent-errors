# -*- coding: utf-8 -*-
"""Сводный отчёт сравнения Эва ↔ Mem0 → отчёт.md (из судья_А/Б.json — второй прогон судьи, и *_прогон1.json)."""
import io
import json
import os

П = os.path.dirname(os.path.abspath(__file__))
# Где я (Claude) не согласен с судьёй после сверки с сырыми данными — пометка в таблице, счёт судьи не меняется.
ОГОВОРКИ = {("Б", 17, "эва"): "по сырым данным тихая: предупреждения в ответе нет; сегодня правдой осталась Felleskjøpet",
            ("А", 27, "mem0"): "мягко: Олегу вопроса нет, противоречие только в тексте памяти",
            ("Б", 10, "mem0"): "мягко: ответ «данные расходятся», вывод сделал судья по пометке «ассистент»",
            ("Б", 14, "mem0"): "судья колеблется: в 1-м прогоне ✓, во 2-м ✗"}


def знак(р):
    return "—" if р["ok"] is None else ("✓" if р["ok"] else ("✗ тихая" if р["тихая"] else "✗"))


стр = ["# Сравнение памяти: Эва ↔ Mem0 — 20.10.2026", "",
       "Условия: Mem0 2.2.1 (`pip install mem0ai`, без дополнений), по умолчанию; LLM claude-sonnet-5-5, векторы OpenAI "
       "text-embedding-3-small, хранилище по умолчанию (qdrant локально, папка внутри сравнения), телеметрия Mem0 выключена. "
       "Эва — C:\\EVA_MEMORY через MCP по HTTP, временная база, «сегодня» = 19.10.2026. Слова Олега у Mem0 — сообщение "
       "пользователя, «Эва сказала» — ассистента, «поправь» — новое сообщение, вопросы — search как есть, «что поменялось» — "
       "get_all. Единый судья: claude-sonnet-5-5, одни подсказки для обеих, система судье не называется; шаг 1 — ответ по "
       "данным (ожидания не видит), шаг 2 — сверка с ожиданием Олега. По одному прогону каждой системы на набор.", ""]
итоги = {}
for н in ("А", "Б"):
    д = json.load(io.open(os.path.join(П, f"судья_{н}.json"), encoding="utf-8"))
    д1 = json.load(io.open(os.path.join(П, f"судья_{н}_прогон1.json"), encoding="utf-8"))
    N = len(д["строки"])
    с = {s: (sum(1 for р in д["строки"] if р[s]["ok"]), sum(1 for р in д["строки"] if р[s]["тихая"])) for s in ("эва", "mem0")}
    с1 = {s: (sum(1 for р in д1["строки"] if р[s]["ok"]), sum(1 for р in д1["строки"] if р[s]["тихая"])) for s in ("эва", "mem0")}
    итоги[н] = (N, с, с1, д)
    стр += [f"## Набор {н} — {N} шагов", "",
            f"| | Эва | Mem0 |", "|---|---|---|",
            f"| судья, 2-й прогон (основной) | **{с['эва'][0]}/{N}**, тихих {с['эва'][1]} | **{с['mem0'][0]}/{N}**, тихих {с['mem0'][1]} |",
            f"| судья, 1-й прогон (с моими ошибками обвязки) | {с1['эва'][0]}/{N}, тихих {с1['эва'][1]} | {с1['mem0'][0]}/{N}, тихих {с1['mem0'][1]} |",
            f"| время прогона | {д['сек']['эва']} с | {д['сек']['mem0']} с |",
            f"| расход системы | ${д['расход']['эва']['usd']} (Sonnet {д['расход']['эва']['sonnet_вызовов']}, DeepSeek {д['расход']['эва']['deepseek_вызовов']}) "
            f"| ${д['расход']['mem0']['usd']} (Sonnet {д['расход']['mem0']['sonnet_вызовов']}, {д['расход']['mem0']['sonnet_in']} ток. на входе) |", "",
            "| № | шаг | ожидание | Эва | Mem0 | заметки |", "|---|---|---|---|---|---|"]
    for р in д["строки"]:
        з = "; ".join(f"{'Эва' if s == 'эва' else 'Mem0'}: {ОГОВОРКИ[(н, р['№'], s)]}" for s in ("эва", "mem0") if (н, р["№"], s) in ОГОВОРКИ)
        стр.append(f"| {р['№']} | {р['задание']} | {р['ожидание']} | {знак(р['эва'])} | {знак(р['mem0'])} | {з} |")
    стр += ["", "Ответы судьи и почему — по шагам в `судья_{0}.json` (сырые данные систем — `сырые_{0}_*.json`).".format(н), ""]
io.open(os.path.join(П, "отчёт.md"), "w", encoding="utf-8").write("\n".join(стр))
print("\n".join(стр[:3]))
for н, (N, с, с1, _) in итоги.items():
    print(н, с, с1)
