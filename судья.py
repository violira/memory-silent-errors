"""Единый судья (20.10.2026): одна модель — claude-sonnet-5-5, одни и те же подсказки для обеих систем; какая система —
судье не говорится. Шаг 1 — ответ по данным системы (ожидания не видит), «не знаю», если в данных нет. Шаг 2 — сверка
ответа с ожиданием Олега (ok / тихая / почему). Сырые данные, ответы и сверки — в судья_<набор>.json, итог — в
сравнение_итог.md. python судья.py"""
